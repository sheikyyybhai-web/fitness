// -----------------------------------------------------------------------------
// Nutrient Scaling & Computation Utility
// -----------------------------------------------------------------------------
export interface ScaledNutrients {
  quantityG: number;
  calories: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
  saturatedFatG: number | null;
  fiberG: number;
  sugarsG: number | null;
  cholesterolMg: number | null;
  vitA_ug: number | null;
  vitB12_ug: number | null;
  vitC_mg: number | null;
  vitD_ug: number | null;
  calcium_mg: number | null;
  iron_mg: number | null;
  magnesium_mg: number | null;
  potassium_mg: number | null;
  sodium_mg: number | null;
  zinc_mg: number | null;
}

export function scaleNutrients(food: FoodItem, quantityG: number): ScaledNutrients {
  const ratio = Math.max(0, quantityG) / 100;
  const round1 = (val: number | null | undefined): number | null => 
    val != null ? Math.round(val * ratio * 10) / 10 : null;

  return {
    quantityG,
    calories: Math.round(food.caloriesPer100g * ratio),
    proteinG: Math.round(food.proteinPer100g * ratio * 10) / 10,
    carbsG: Math.round(food.carbsPer100g * ratio * 10) / 10,
    fatG: Math.round(food.fatPer100g * ratio * 10) / 10,
    saturatedFatG: round1(food.saturatedFatPer100g),
    fiberG: Math.round(food.fiberPer100g * ratio * 10) / 10,
    sugarsG: round1(food.sugarsPer100g),
    cholesterolMg: round1(food.cholesterolMgPer100g),
    vitA_ug: round1(food.vitA_ug),
    vitB12_ug: round1(food.vitB12_ug),
    vitC_mg: round1(food.vitC_mg),
    vitD_ug: round1(food.vitD_ug),
    calcium_mg: round1(food.calcium_mg),
    iron_mg: round1(food.iron_mg),
    magnesium_mg: round1(food.magnesium_mg),
    potassium_mg: round1(food.potassium_mg),
    sodium_mg: round1(food.sodium_mg),
    zinc_mg: round1(food.zinc_mg)
  };
}

// -----------------------------------------------------------------------------
// Search & Filter Operations
// -----------------------------------------------------------------------------
export interface FoodFilterOptions {
  searchQuery?: string;
  categoryId?: string;
  dietaryType?: DietaryType | 'all';
  preparationState?: PreparationState | 'all';
  minProteinPer100g?: number;
  maxCaloriesPer100g?: number;
  highFiberOnly?: boolean;
  sortBy?: 'protein_desc' | 'calories_asc' | 'calories_desc' | 'fiber_desc' | 'name_asc';
}

export function filterFoods(foods: FoodItem[], options: FoodFilterOptions): FoodItem[] {
  return foods.filter(food => {
    // 1. Search Query
    if (options.searchQuery && options.searchQuery.trim() !== '') {
      const q = options.searchQuery.toLowerCase();
      const matchName = food.name.toLowerCase().includes(q);
      const matchDesc = food.description.toLowerCase().includes(q);
      const matchCat = food.categoryName?.toLowerCase().includes(q);
      if (!matchName && !matchDesc && !matchCat) return false;
    }

    // 2. Category Filter
    if (options.categoryId && options.categoryId !== 'all') {
      if (food.categoryId !== options.categoryId) return false;
    }

    // 3. Dietary Type Filter
    if (options.dietaryType && options.dietaryType !== 'all') {
      if (food.dietaryType !== options.dietaryType) return false;
    }

    // 4. Preparation State Filter
    if (options.preparationState && options.preparationState !== 'all') {
      if (food.preparationState !== options.preparationState) return false;
    }

    // 5. Min Protein Filter
    if (options.minProteinPer100g != null && options.minProteinPer100g > 0) {
      if (food.proteinPer100g < options.minProteinPer100g) return false;
    }

    // 6. Max Calories Filter
    if (options.maxCaloriesPer100g != null && options.maxCaloriesPer100g > 0) {
      if (food.caloriesPer100g > options.maxCaloriesPer100g) return false;
    }

    // 7. High Fiber Filter (>= 5g / 100g)
    if (options.highFiberOnly) {
      if (food.fiberPer100g < 5.0) return false;
    }

    return true;
  }).sort((a, b) => {
    switch (options.sortBy) {
      case 'protein_desc':
        return b.proteinPer100g - a.proteinPer100g;
      case 'calories_asc':
        return a.caloriesPer100g - b.caloriesPer100g;
      case 'calories_desc':
        return b.caloriesPer100g - a.caloriesPer100g;
      case 'fiber_desc':
        return b.fiberPer100g - a.fiberPer100g;
      case 'name_asc':
      default:
        return a.name.localeCompare(b.name);
    }
  });
}
